/**
 * Исходящие сообщения в мессенджер (канал уведомлений рядом с СМС и почтой, ADR-0008).
 * Вендор MVP — MAX Bot API (добавлен по слову владельца 13.08.2026).
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ ПОРТ, А НЕ РАСШИРЕНИЕ SmsProvider: адресация другая. У СМС адрес — телефон в
 * E.164, у мессенджера — идентификатор чата, выданный платформой при первом обращении пользователя
 * К БОТУ. Их нельзя подставлять одно вместо другого: отправка «по телефону» в мессенджер невозможна,
 * пока человек сам не написал боту. Это ограничение канала, а не нашей реализации, и его надо
 * держать в типе, чтобы никто не написал «шлём код в MAX по номеру».
 */
export interface MessengerMessage {
  /** Идентификатор чата, выданный платформой (НЕ телефон и НЕ наш user_id). */
  chatId: string;
  text: string;
}

/**
 * ИСХОД ОТПРАВКИ — ТРИ СОСТОЯНИЯ, А НЕ БУЛЕВО (находка №131).
 *
 * ЧТО БЫЛО ЗАМЕРЕНО. Поле называлось `accepted: boolean` и НЕ несло ни строки о своём смысле —
 * поэтому две реализации одного порта возвращали ПРОТИВОПОЛОЖНОЕ, обе формально соответствуя типу:
 *  · боевой адаптер на ответе «200 без mid» → `accepted:false` = «площадка не подтвердила приём»
 *    (запрос при этом, скорее всего, ДОШЁЛ);
 *  · заглушка (канал спит) → `accepted:true` = «не отправлено вовсе».
 * Потребителю оба выглядели как одно поле с одним смыслом. Естественное прочтение «false → повторить»
 * даёт ДУБЛЬ живому человеку, «true → порядок» — тихую потерю уведомления. Третьей дороги порт не давал.
 *
 * ЧТО ЗНАЧИТ КАЖДОЕ ЗНАЧЕНИЕ (это и есть объявленный смысл, которого не было):
 *  · `accepted`    — площадка ПОДТВЕРДИЛА приём (вернула идентификатор сообщения). Повторять НЕ надо.
 *  · `unconfirmed` — ответ получен, но приёма он не подтверждает. Запрос МОГ ДОЙТИ ⇒ слепой повтор
 *                    способен создать ДУБЛЬ у получателя; повторять только с ключом идемпотентности.
 *                    Родня признака `ProviderError.mayHaveArrived`, но живёт на УРОВНЕ ПОРТА,
 *                    потому что этот исход — не ошибка и класса ошибки у него нет по построению.
 *  · `not-sent`    — мы не отправляли вовсе (канал спит / заглушка). Повтор БЕЗОПАСЕН, но сначала
 *                    надо включить канал: сообщение до человека не дошло и не дойдёт.
 *
 * Отказы площадки и двери сюда НЕ приходят — они бросаются `ProviderError` (см. `provider-error.ts`).
 */
export type MessengerOutcome = 'accepted' | 'unconfirmed' | 'not-sent';

export interface MessengerSendResult {
  outcome: MessengerOutcome;
  /** Идентификатор сообщения у вендора, когда он его вернул (null у заглушки и у `unconfirmed`). */
  providerMessageId: string | null;
}

export interface MessengerProvider {
  sendMessage(msg: MessengerMessage): Promise<MessengerSendResult>;
}
