/**
 * Исходящие сообщения в мессенджер (канал уведомлений рядом с СМС и почтой, ADR-0008).
 * Вендор MVP — MAX Bot API (добавлен по слову владельца 13.08.2026).
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ ПОРТ, А НЕ РАСШИРЕНИЕ SmsProvider: адресация другая. У СМС адрес — телефон в
 * E.164, у мессенджера — идентификатор чата, выданный платформой при первом обращении пользователя
 * К БОТУ. Их нельзя подставлять одно вместо другого: отправка «по телефону» в мессенджер невозможна,
 * пока человек сам не написал боту. Это ограничение канала, а не нашей реализации, и его надо
 * держать в типе, чтобы никто не написал «шлём код в MAX по номеру».
 */
export interface MessengerMessage {
  /** Идентификатор чата, выданный платформой (НЕ телефон и НЕ наш user_id). */
  chatId: string;
  text: string;
}

export interface MessengerSendResult {
  accepted: boolean;
  /** Идентификатор сообщения у вендора, когда он его вернул (null у заглушки). */
  providerMessageId: string | null;
}

export interface MessengerProvider {
  sendMessage(msg: MessengerMessage): Promise<MessengerSendResult>;
}
