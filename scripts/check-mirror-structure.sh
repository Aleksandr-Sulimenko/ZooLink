#!/usr/bin/env bash
#
# check-mirror-structure.sh — СВЕРКА ЗЕРКАЛ EN↔RU ПО СТРУКТУРЕ, А НЕ ПО РАЗМЕРУ.
#
# ЗАЧЕМ. Канон живёт в двух зеркалах (docs/ и docsRU/), и расходятся они МОЛЧА: правку вносят в одну
# сторону, вторая остаётся вчерашней и продолжает утверждать отменённое. Замерено 20.08.2026 на
# ADR-0017: английская сторона ЗАЧЕРКНУЛА правило «зашитые в код хосты гейту не видны и управляются
# ревью по ADR-0008» (обе половины ложны), а русская несла его как действующее ещё неделю — то есть
# читатель по-русски получал ровно ту ложь, которую по-английски уже сняли.
#
# ПОЧЕМУ ПО СТРУКТУРЕ, А НЕ ПО ОБЪЁМУ. Сравнение размеров — гадание: перевод законно длиннее или
# короче. Скелет заголовков (уровень + порядок + число) — это КОНТРАКТ документа: раздел, который
# есть с одной стороны и отсутствует с другой, виден сразу и без знания языка.
# ЧЕГО ПРИБОР НЕ ДЕЛАЕТ И НЕ ОБЕЩАЕТ: он не читает СМЫСЛ. Абзац можно перевести наоборот, и скелет
# этого не покажет. Это названо здесь, чтобы зелёное не читалось шире, чем оно есть.
#
# ТРИ СОСТОЯНИЯ (ADR-0027): 0 = скелеты совпали · 1 = расхождение · 2 = НЕ ЗНАЮ (нет пары, пусто).
set -uo pipefail

case "${1:-}" in
  ''|--подробно) ;;
  *) echo "::error::неизвестный аргумент «$1». Допустимо: без аргументов или --подробно" >&2; exit 2 ;;
esac

root="$(git rev-parse --show-toplevel 2>/dev/null)" || { echo "::error::НЕ ЗНАЮ — не нашла корень дерева"; exit 2; }
cd "$root" || exit 2

fail=0; checked=0; missing=0; known=0
skeleton(){ grep -oE "^#{1,6} " "$1" | tr -d ' \n'; }

for en in docs/04-decisions/*.md; do
  [ -f "$en" ] || continue
  ru="docsRU/${en#docs/}"
  base="$(basename "$en")"
  if [ ! -f "$ru" ]; then
    echo "::error::НЕТ РУССКОЙ ПАРЫ: $base — зеркало объявлено, а стороны нет"; missing=$((missing+1)); continue
  fi
  # ИЗВЕСТНОЕ РАСХОЖДЕНИЕ ПРОПУСКАЕТСЯ ПОИМЁННО И ВСЛУХ (см. scripts/mirror-known-gaps.txt).
  if [ -f scripts/mirror-known-gaps.txt ] && grep -qxF "$base" <(grep -vE '^#|^$' scripts/mirror-known-gaps.txt); then
    known=$((known+1)); echo "  ⚠️ ИЗВЕСТНОЕ расхождение (объявлено): $base — не проверяется, но и не забыто"
    continue
  fi
  a="$(skeleton "$en")"; b="$(skeleton "$ru")"
  if [ -z "$a" ] || [ -z "$b" ]; then
    echo "::error::НЕ ЗНАЮ — у $base не читается скелет хотя бы с одной стороны (пустой файл?)"; exit 2
  fi
  checked=$((checked+1))
  if [ "$a" = "$b" ]; then
    [ "${1:-}" = "--подробно" ] && echo "  ok   $base — скелет совпал ($(grep -cE '^#{1,6} ' "$en") заголовков)"
  else
    echo "::error::$base — СКЕЛЕТЫ РАСХОДЯТСЯ: en «$a» ru «$b»"
    if [ "${1:-}" = "--подробно" ]; then
      diff <(grep -E "^#{1,6} " "$en") <(grep -E "^#{1,6} " "$ru") | head -20
    fi
    fail=$((fail+1))
  fi
done

echo "  сверено пар: $checked · расходятся: $fail · без русской пары: $missing · ИЗВЕСТНОЕ объявленное: $known"
# ЧИСЛО ПРОГНАННОГО СВЕРЯЕТСЯ С ОЖИДАЕМЫМ, А НЕ ПРОСТО ПЕЧАТАЕТСЯ: «0 пар» — это НЕ «всё чисто».
[ "$checked" -gt 0 ] || { echo "::error::НЕ ЗНАЮ — не сверено НИ ОДНОЙ пары (каталог пуст или переименован)"; exit 2; }
[ "$missing" -eq 0 ] || exit 1
[ "$fail" -eq 0 ] || exit 1
echo "✅ скелеты зеркал совпадают во всех $checked сверенных парах (структура; СМЫСЛ прибор не читает; известного объявлено: $known)"
