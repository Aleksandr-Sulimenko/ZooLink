#!/usr/bin/env bash
# РУБИЛЬНИК ОТКАТА пака «исходящий периметр в одной двери + канал MAX» (ADR-0017/0008).
#
# ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ, А НЕ «сделай git revert руками». Требование формы гейта от 14.08.2026,
# и оно выросло из живого случая: у окна из трёх паков рубильник возвращал ОДИН файл из трёх, а
# рядом лежали ТРИ протухших набора с тем же именем — и голое имя увело держателя к чужому набору,
# который вернул бы дерево на пять дней назад И НАПЕЧАТАЛ ✓. Поэтому здесь: полный путь в имени,
# ЯВНЫЙ перечень радиуса, и проверка ПОСЛЕ отката, что вернулось ВСЁ, а не часть.
#
# ЧТО ДЕЛАЕТ: возвращает ВСЕ пути перечня PATHS к состоянию ДО коммита $PACK (родитель), затем
# СВЕРЯЕТ каждый путь побайтово с родителем и печатает число вернувшихся. Не трогает ничего вне
# перечня. ЧИСЛА ПУТЕЙ В ШАПКЕ БОЛЬШЕ НЕТ (находка №153): оно было вписано руками, разошлось с
# перечнем (шапка «14», прогон «15») — и человек в аварии сверял вывод с ложью ровно в тот миг,
# когда решал, дёргать ли рубильник. Число печатает САМ прогон, из ${#PATHS[@]}.
#
# КОДЫ: 0 — откат полный, все пути совпали с родителем · 1 — вернулось НЕ ВСЁ (назовёт какие) ·
#       2 — отказ ДО правок (не тот репозиторий, коммит не найден, грязное дерево по этим путям).
#
# ГДЕ ЭТОТ ПРИБОР ЗАПУСКАЕТСЯ, СКАЗАНО ПРЯМО (находка №151, 25.08.2026). Это прибор МАШИНЫ С
# ПОЛНЫМ GIT-ДЕРЕВОМ — рабочей машины или раннера с fetch-depth: 0. Он НЕ запускается там, где
# живёт боевой процесс: образ backend/Dockerfile (ADR-0009) git-дерева не несёт, и никакой флаг
# этого не изменит. Откат В БОЮ делается ПЕРЕСБОРКОЙ ОБРАЗА с прежнего тега, а этот файл говорит,
# ЧТО именно вернуть и чем это оплачено. В МЕЛКОМ клоне (`git clone --depth 1` — дефолт
# actions/checkout) коммита пака нет: лечится `git fetch --unshallow`, и отказ теперь это называет.
#
# ЗАПУСК:  bash scripts/rollback-outbound-perimeter.sh [--проверить]
#          --проверить: только сказать, что БЫ откатилось, ничего не меняя.
set -uo pipefail
export LC_ALL=C

PACK="f6a7e7cbd6f2cc142b2c922b631d6e86fe5087b0"   # «исходящий периметр в ОДНОЙ двери + канал MAX»

# ДВА ПУТИ ДОБАВЛЕНЫ 17.08.2026 ПО НАХОДКЕ №46 РЕ-ГЕЙТА, и оба — про полноту, а не про удобство:
#  · provider-error.ts несёт поле `code` и `extractRuntimeErrorCode`; без него откат вернул бы
#    http.util.ts к версии БЕЗ извлечения кода, оставив половину лечения в дереве, — и напечатал
#    бы «12 из 12 совпали». Это буквально класс, названный в шапке этого же файла;
#  · env.validation.spec.ts — оси приёмки IPv6/флага стендов; откат кода без отката его осей даёт
#    красный свод на ровном месте и читается как поломка, а не как откат.
PATHS=(
  .env.example
  backend/src/config/env.validation.ts
  backend/src/config/env.validation.spec.ts
  # Дописан 31.08.2026 ПО КРАСНОМУ СВОЕЙ ЖЕ ОСИ (3): лечение №174 тронуло этот свод, и перечень
  # перестал покрывать пак. Ось назвала файл сама — ровно то, ради чего её единицей замера сделали
  # ЖИВОЕ ДЕРЕВО, а не коммит (находка №118). Без него откат снял бы код и оставил свод на его
  # поведение: дерево не собралось бы, и человек в аварии получил бы ВТОРУЮ аварию.
  backend/src/config/gen-env.spec.ts
  backend/src/lib/providers/provider-error.ts
  backend/src/lib/providers/http.util.ts
  backend/src/lib/providers/http.util.spec.ts
  backend/src/lib/providers/index.ts
  backend/src/lib/providers/provider.tokens.ts
  backend/src/lib/providers/providers.module.ts
  backend/src/lib/providers/providers.module.spec.ts
  backend/src/lib/providers/messenger/messenger-provider.port.ts
  backend/src/lib/providers/messenger/max-bot.adapter.ts
  backend/src/lib/providers/messenger/max-bot.adapter.spec.ts
  backend/src/lib/providers/messenger/stub-messenger.adapter.ts
  scripts/check-rf-residency.sh
)

die(){ printf 'rollback: ОТКАЗ — %s\n' "$1" >&2; exit 2; }

# НЕИЗВЕСТНЫЙ АРГУМЕНТ — ОТКАЗ, А НЕ «ДЕЛАЙ ПО-НАСТОЯЩЕМУ». Скрипт знал ровно один флаг
# (кириллический --проверить), и ЛЮБОЙ другой аргумент проходил все сравнения, означая боевой
# прогон. ЗАМЕРЕНО backend-лейном на клоне (круг 2): на ЧИСТОМ дереве команда `--dry-run` выполнила
# ПОЛНЫЙ ОТКАТ — 14 файлов изменено, 5 удалено, — напечатала «✓ откат ПОЛНЫЙ» и вышла rc=0.
# Оператор просил ПОКАЗАТЬ, получил разрушение и зелёный отчёт. Защита «грязное дерево» этого не
# ловила по построению: на чистом дереве, то есть ровно тогда, когда рубильник и нужен, она молчит.
# --самопроверка — СВОД САМОГО РУБИЛЬНИКА (добавлено 18.08.2026).
# ЗАЧЕМ: замер держателя по флоту — 26 из 39 shell-приборов не стерегло НИЧЕГО, и рубильник был
# среди них: оба его дефекта («любой неизвестный аргумент = боевой прогон» и «печатает 12 из 12,
# не покрывая два файла предмета») нашли ЧУЖИЕ руки, а после починки их снова не стерегло ничто.
# Свод живёт ВНУТРИ прибора: внешний до чужих сред не доезжает, а рубильник запускают именно там.
# Все пробы идут на ОДНОРАЗОВОМ КЛОНЕ — боевого дерева самопроверка не касается ни разу.
if [ "${1:-}" = "--самопроверка" ]; then
  git rev-parse --git-dir >/dev/null 2>&1 || die "здесь не git-репозиторий (cwd=$PWD)"
  root="$(git rev-parse --show-toplevel)" || die "не нашла корень дерева"
  # ТОТ ЖЕ ТРЁХСОСТОЯНИЙНЫЙ ДИАГНОЗ, ЧТО И У БОЕВОГО ПУТИ (находка №151). Свод рубильника едет в
  # CI, а CI по умолчанию клонирует МЕЛКО — без этой строки шаг падал бы rc=2 «в клоне нет коммита
  # пака», и это читалось бы как «прибор сломан», а не как «шагу не дали историю».
  if [ "$(git rev-parse --is-shallow-repository 2>/dev/null)" = "true" ]; then
    die "самопроверке нужна ПОЛНАЯ история (дерево мелкое, глубина $(git rev-list --count HEAD 2>/dev/null || echo '?')): свод воспроизводит откат на клоне коммита пака.
    ЛЕЧЕНИЕ: git fetch --unshallow   (в CI — actions/checkout с fetch-depth: 0). Это НЕ поломка прибора: истории просто не дали."
  fi
  me="$root/scripts/$(basename "$0")"
  work="$(mktemp -d)"; trap 'rm -rf "$work"' EXIT
  git clone --quiet --shared --no-checkout "$root" "$work/clone" 2>/dev/null || die "не смогла сделать одноразовый клон"
  git -C "$work/clone" checkout --quiet "$PACK" 2>/dev/null || die "в клоне нет коммита пака"
  cp "$me" "$work/clone/scripts/$(basename "$0")"
  ran=0; fails=0; declared=8  # +1 (28.08): «отказ на МЕЛКОМ дереве называет лечение» (страж №151); +1 (31.08): «последний advice_line ИСПОЛНИМ из названного advice_dirа» (страж №141)

  снимок(){ (cd "$1" && git ls-files -s | sha256sum | cut -c1-16); }

  # (1) НЕИЗВЕСТНЫЙ АРГУМЕНТ: rc=2 и дерево НЕ ТРОНУТО (проверяем и код, и дерево — код без дерева
  #     доказывал бы лишь намерение).
  before="$(снимок "$work/clone")"
  (cd "$work/clone" && bash "scripts/$(basename "$0")" --dry-run >/dev/null 2>&1); rc=$?
  after="$(снимок "$work/clone")"; ran=$((ran+1))
  if [ "$rc" = 2 ] && [ "$before" = "$after" ]; then echo "  ok   неизвестный аргумент → rc=2, дерево не тронуто"
  else echo "::error::неизвестный аргумент → rc=$rc, дерево $([ "$before" = "$after" ] && echo цело || echo ИЗМЕНЕНО) — это тот самый дефект, что уже был замерен"; fails=$((fails+1)); fi

  # (2) --проверить НЕ МЕНЯЕТ ДЕРЕВО (побайтово по индексу, а не «на глаз»).
  before="$(снимок "$work/clone")"
  (cd "$work/clone" && bash "scripts/$(basename "$0")" --проверить >/dev/null 2>&1); rc=$?
  after="$(снимок "$work/clone")"; ran=$((ran+1))
  if [ "$rc" = 0 ] && [ "$before" = "$after" ]; then echo "  ok   --проверить → rc=0, дерево побайтово то же"
  else echo "::error::--проверить → rc=$rc, дерево $([ "$before" = "$after" ] && echo цело || echo ИЗМЕНЕНО)"; fails=$((fails+1)); fi

  # (3) ПЕРЕЧЕНЬ ПОКРЫВАЕТ КОММИТ ПАКА. Иначе откат вернёт часть и напечатает «полный» — класс,
  #     названный в шапке этого же файла и уже случившийся дважды.
  # ЕДИНИЦА ЗАМЕРА = ЖИВОЕ ДЕРЕВО, А НЕ КОММИТ (находка №118, замер 20.08). Прежде сверялись ТОЛЬКО
  # с `PACK^..PACK` — и файл, рождённый ПОСЛЕ коммита, в перечень не попадал, а проверка печатала
  # «покрывает все пути». Живой случай: providers.module.spec.ts с шестью осями круга 4. Откат снял
  # бы код и оставил свод на его экспорты — дерево не собралось бы, и человек в аварии получил бы
  # вторую аварию. Теперь берём ОБЪЕДИНЕНИЕ: коммит пака ∪ незакоммиченные правки рабочего дерева.
  # ИЗВЕСТНЫЕ ИСКЛЮЧЕНИЯ НАЗВАНЫ ПОИМЁННО, а не молчат: документы канона (у них свой рубильник) и
  # сам этот файл (рубильник не откатывает себя).
  missing=""
  while IFS= read -r f; do
    [ -n "$f" ] || continue
    # ОБЛАСТЬ ПАКА НАЗВАНА ЯВНО. Рабочее дерево содержит и ЧУЖИЕ правки (например `.claude/*` —
    # настройки харнесса), и требовать их отката значило бы забрать чужое — сегодняшний закон флота.
    # Поэтому сверяем только там, где пак ХОЗЯИН, и исключения перечисляем поимённо.
    case "$f" in
      .env.example|backend/src/config/*|backend/src/lib/providers/*|scripts/check-rf-residency.sh) ;;
      *) continue ;;
    esac
    case "$f" in
      docs/04-decisions/*|docsRU/04-decisions/*) continue ;;
      scripts/rollback-outbound-perimeter.sh|scripts/rollback-perimeter-docs.sh) continue ;;
    esac
    case " ${PATHS[*]} " in *" $f "*) ;; *) missing="$missing $f" ;; esac
  done < <( { git -C "$work/clone" diff --name-only "$PACK^" "$PACK" 2>/dev/null
              git -C "$root" diff --name-only "$PACK" -- 2>/dev/null; } | sort -u )
  ran=$((ran+1))
  if [ -z "$missing" ]; then echo "  ok   перечень покрывает все пути коммита пака (${#PATHS[@]} шт.)"
  else echo "::error::в перечне НЕТ путей коммита пака:$missing — откат вернёт часть и напечатает «полный»"; fails=$((fails+1)); fi

  # (4) МУТАНТ НА (3): изъять путь из перечня — проверка ОБЯЗАНА покраснеть И НАЗВАТЬ его.
  #     Без пятого довода (что именно названо) красное не доказывает починку — урок круга 3.
  victim="${PATHS[1]}"
  sed "s|^  ${victim}$||" "$me" > "$work/clone/scripts/mutant.sh"
  out="$( (cd "$work/clone" && bash scripts/mutant.sh --самопроверка 2>&1) )"; ran=$((ran+1))
  if printf '%s' "$out" | grep -q "в перечне НЕТ путей коммита пака" && printf '%s' "$out" | grep -qF "$victim"; then
    echo "  ok   мутант «изъят путь $victim» → проверка (3) краснеет и НАЗЫВАЕТ его"
  else echo "::error::мутант «изъят путь $victim» не покраснел или не назвал путь — проверку (3) не стережёт ничто"; fails=$((fails+1)); fi
  cp "$me" "$work/clone/scripts/$(basename "$0")"

  # (5) БОЕВОЙ ОТКАТ НА КЛОНЕ и повторный прогон: «уже откачено», а не отказ по чужой работе.
  (cd "$work/clone" && bash "scripts/$(basename "$0")" >/dev/null 2>&1); rc1=$?
  out2="$( (cd "$work/clone" && bash "scripts/$(basename "$0")" 2>&1) )"; rc2=$?
  ran=$((ran+1))
  if [ "$rc1" = 0 ] && [ "$rc2" = 0 ] && printf '%s' "$out2" | grep -q "УЖЕ применён"; then
    echo "  ok   боевой откат на клоне → rc=0, повтор распознан как «уже применён»"
  else echo "::error::боевой откат на клоне: первый rc=$rc1, повтор rc=$rc2 — идемпотентность не держится"; fails=$((fails+1)); fi

  # НОЛЬ ПРОГНАННОГО = НЕ ЗНАЮ (ADR-0027): без этой строки пустой свод печатал бы «пройдено».
  # ОСЬ НА ТО, ЧТО РУБИЛЬНИК НАЗЫВАЕТ ЦЕНУ (находка №33): молчащий рубильник читается как
  # «вернуть как было», хотя снимает дверь целиком.
  ran=$((ran+1))
  # ИМЯ ПЕРЕМЕННОЙ ТОЛЬКО ASCII. Кириллица законна у ФУНКЦИЙ этого файла (чем_платим, снимок), но
  # НЕ у присваивания: bash читает «цена_текст=…» как ИМЯ КОМАНДЫ и падает «No such file or
  # directory», а ось при этом краснеет по постороннему поводу. Поймано этой же самопроверкой
  # 25.08.2026 при первой редакции лечения №150.
  price_text="$(bash "${BASH_SOURCE[0]}" --проверить 2>&1)"
  # ДВА ТРЕБОВАНИЯ, А НЕ ОДНО (находка №150, 25.08.2026). Прежде ось спрашивала только «есть ли
  # заголовок ЦЕНА ОТКАТА» — и была зелёной, пока цена перечисляла ЧЕТЫРЕ потери из пяти. Пятая —
  # что откат снимает и САМУ СИГНАЛИЗАЦИЮ (ось 6 CI-гейта резидентности едет в перечне откатываемых
  # путей). Заголовок без этой строки читается как «цена названа полностью», хотя названа не вся.
  # ИСКАТЬ ИМЯ ФАЙЛА ЗДЕСЬ НЕЛЬЗЯ (поймано на первой редакции этого лечения): `--проверить`
  # печатает и ПЕРЕЧЕНЬ ПУТЕЙ, где scripts/check-rf-residency.sh стоит всегда, — ось была бы
  # зелёной при полностью вырезанной пятой потере. Ищем оборот, живущий ТОЛЬКО в тексте цены.
  if printf '%s' "$price_text" | grep -q "ЦЕНА ОТКАТА" \
     && printf '%s' "$price_text" | grep -q "ось 6 CI-гейта"; then
    echo "  ok   рубильник называет ЦЕНУ отката (дверь, редиректы, потолок, канал MAX) И пятую потерю — сигнализацию (ось 6 CI)"
  elif printf '%s' "$price_text" | grep -q "ЦЕНА ОТКАТА"; then
    echo "::error::цена названа НЕПОЛНО: заголовок «ЦЕНА ОТКАТА» есть, а пятая потеря (откат scripts/check-rf-residency.sh снимает ось 6 CI — надзор за исходящими адресами) НЕ названа. Замерено: после такого отката гейт печатает ✅ на адаптере с зарубежным хостом"; fails=$((fails+1))
  else
    echo "::error::рубильник молчит о том, что снимает — «12 из 12 совпали» читается как «всё в порядке»"; fails=$((fails+1))
  fi
  # (7) ОТКАЗ НА МЕЛКОМ ДЕРЕВЕ РАЗЛИЧАЕТ ДВА МИРА И НАЗЫВАЕТ ПУТЬ НАРУЖУ (страж находки №151).
  #     Лечение приехало 25.08 без оси, а «починена» обязана назвать стража: без него следующая
  #     правка текста отказа вернула бы ложный диагноз «вы в том репозитории?» молча.
  #     ЕДИНИЦА ЗАМЕРА — МЕЛКИЙ КЛОН, а не флаг: спрашивать `--is-shallow-repository` у полного
  #     дерева значило бы проверять СВОЮ ВЫДУМКУ о мелком дереве. Клон делаем глубиной 1 от
  #     ЖИВОГО HEAD, где коммита пака заведомо нет, — то самое состояние, в котором оператор
  #     дёргает рубильник в аварии (дефолт actions/checkout и любого выката).
  ran=$((ran+1))
  shallow_dir="$work/shallow"
  if git clone --quiet --depth 1 "file://$root" "$shallow_dir" 2>/dev/null \
     && [ "$(git -C "$shallow_dir" rev-parse --is-shallow-repository 2>/dev/null)" = "true" ]; then
    cp "$me" "$shallow_dir/scripts/" 2>/dev/null || true
    refusal="$( (cd "$shallow_dir" && bash "scripts/$(basename "$0")" --проверить) 2>&1 )"; rc_shallow=$?
    if [ "$rc_shallow" != 0 ] \
       && printf '%s' "$refusal" | grep -q -- "--unshallow" \
       && printf '%s' "$refusal" | grep -q "МЕЛКОЕ"; then
      echo "  ok   мелкое дерево → отказ НАЗЫВАЕТ причину (история обрезана) и лечение (--unshallow), а не «другой репозиторий»"
    else
      echo "::error::на МЕЛКОМ дереве отказ не назвал ни обрезанную историю, ни git fetch --unshallow (rc=$rc_shallow) — оператор в аварии пойдёт проверять то, что и так верно. Ответ был: $(printf '%s' "$refusal" | head -2)"; fails=$((fails+1))
    fi
  else
    echo "::error::не удалось собрать МЕЛКИЙ клон для оси 7 — ось НЕ ПРОГНАНА (это «не знаю», а не «пройдено»)"; fails=$((fails+1))
  fi

  # (8) ПОСЛЕДНИЙ СОВЕТ РУБИЛЬНИКА ИСПОЛНИМ ИЗ ТОГО КАТАЛОГА, ГДЕ ОН ОСТАВЛЯЕТ ЧЕЛОВЕКА (страж
  #     находки №141, дописан 31.08.2026). Лечение было сделано 25.08, а стража у него не было —
  #     то есть «починено» держалось на том, что никто не тронет строку. Ось меряет ИСПОЛНИМОСТЬ,
  #     а не наличие текста: (а) advice_line обязан НАЗЫВАТЬ advice_dir, где лежит package.json, и (б) все
  #     названные им npm-script_nameы обязаны СУЩЕСТВОВАТЬ в этом package.json.
  #     ПОЧЕМУ НЕ ПРОГОНЯЕМ ИХ ЗДЕСЬ: typecheck и jest на живом дереве — это минуты и чужая
  #     установка зависимостей; ось стерегла бы среду, а не advice_line. Граница названа вслух.
  ran=$((ran+1))
  # ОБЛАСТЬ ЗАМЕРА НЕ ЗАХВАТЫВАЕТ САМУ СЕБЯ — И ЭТО ПРИШЛОСЬ ЧИНИТЬ ДВАЖДЫ, ВТОРОЙ РАЗ СМЕШНЕЕ.
  # Редакция 1 брала первое вхождение «npm run typecheck» и находила СОБСТВЕННУЮ строку оси, а не
  # печатаемый совет — ось краснела на исправном коде. Редакция 2 добавила фильтр «и содержит
  # printf» — и снова нашла себя, потому что теперь СОБСТВЕННАЯ строка содержала и его.
  # Наш класс «область замера захватила чужое» в самом близком виде: захватила СЕБЯ, и первое
  # лечение расширило совпадение вместо того, чтобы его сузить. Единица замера = строка, которую
  # скрипт ПЕЧАТАЕТ, поэтому якорь ставится на НАЧАЛО строки: только `printf` в начале.
  advice_line="$(grep -E "^[[:space:]]*printf '.*npm run typecheck" "$me" | head -1)"
  advice_dir="$(printf '%s' "$advice_line" | sed -n 's/.*cd \([A-Za-z0-9_.-]*\) *&&.*/\1/p')"
  if [ -z "$advice_line" ] || [ -z "$advice_dir" ]; then
    echo "::error::последний совет рубильника не называет каталог — скопированный из корня, он найдёт СИСТЕМНЫЙ tsc (наборщик TeX) и не прогонит НИ ОДНОЙ проверки (находка №141)"; fails=$((fails+1))
  elif [ ! -f "$root/$advice_dir/package.json" ]; then
    echo "::error::совет зовёт из «$advice_dir», но $advice_dir/package.json НЕ СУЩЕСТВУЕТ — advice_line неисполним"; fails=$((fails+1))
  else
    # ИМЕНА СКРИПТОВ БЕРУТСЯ ИЗ САМОГО СОВЕТА, А НЕ ИЗ ОЖИДАНИЯ ОСИ. Поймано мутантом М-2 при
    # написании этой оси: с фиксированным списком «typecheck lint test» она проверяла наличие ЭТИХ
    # трёх в package.json — и оставалась ЗЕЛЁНОЙ, когда совет звал `npm run typecheck-НЕТ-ТАКОГО`.
    # Ось мерила собственное ожидание вместо артефакта — тот же класс, что у первой редакции,
    # нашедшей СЕБЯ вместо печатаемой строки, только этажом выше.
    # (И здесь же дожил кириллический `$нет` от слепой замены имён — читался как пустое, ошибки не
    # давал, но копил бы имена в никуда. Нашёлся чтением при этой правке.)
    missing_scripts=""
    advice_scripts="$(printf '%s' "$advice_line" | grep -oE 'npm (run [A-Za-z0-9:_-]+|test)' | sed 's/^npm run //; s/^npm //')"
    if [ -z "$advice_scripts" ]; then
      missing_scripts=" (совет не зовёт НИ ОДНОГО npm-скрипта)"
    else
      for script_name in $advice_scripts; do
        grep -q "\"$script_name\"[[:space:]]*:" "$root/$advice_dir/package.json" ||
          missing_scripts="$missing_scripts $script_name"
      done
    fi
    if [ -n "$missing_scripts" ]; then
      echo "::error::advice_line зовёт npm-script_nameы, которых нет в $advice_dir/package.json:$нет — строка выглядит рабочей и не работает"; fails=$((fails+1))
    else
      echo "  ok   последний совет исполним из «$advice_dir»: package.json на месте, скрипты typecheck, lint и test объявлены"
    fi
  fi

  echo "  самопроверка: прогнано $ran из объявленных $declared"
  [ "$ran" = "$declared" ] || { echo "::error::прогнано $ran из $declared — это НЕ ЗНАЮ, а не «пройдено»"; exit 2; }
  [ "$fails" = 0 ] && { echo "✅ самопроверка рубильника пройдена"; exit 0; }
  echo "❌ самопроверка рубильника ПРОВАЛЕНА ($fails)"; exit 1
fi

