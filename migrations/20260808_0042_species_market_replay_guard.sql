-- Migration 0042 — species.market: заслонка против безусловного replay миграции 0007.
-- DRAFT (пак-4, готовится к вкатке ПОСЛЕ коммитов). Схема не меняется: таблиц по-прежнему 41+,
-- ни одной новой колонки/таблицы/constraint — только триггер-заслонка + GUC для легитимного пути.
--
-- ============================================================================
-- ЧТО:
--   Ставит BEFORE UPDATE OF market ON species заслонку trg_species_market_replay_guard, которая
--   отличает СЫРОЙ replay (migrations/20260617_0007_species_market.sql:12 — безусловный
--   `UPDATE species SET market='livestock' WHERE code IN (…9 кодов…)`) от ПРИКЛАДНОГО пути
--   (admin PATCH /v1/admin/reference-data/species/{id}) и:
--     · прикладной путь пропускает БЕЗ ОГРАНИЧЕНИЙ, когда транзакция подняла заслонку
--       set_config('app.reference_data_admin','on',true) — прецедент app.ownership_transfer
--       (migrations/20260626_0023_ownership_transfer_mvp.sql:105-107);
--     · чистый no-op (не меняется НИ ОДНА колонка кроме updated_at) — гасит целиком, RETURN NULL:
--       строка не перезаписывается, updated_at/xmin не двигаются;
--     · сырой replay, пытающийся ПЕРЕЗАПИСАТЬ решение оператора, — гасит ТИХО для вызывающего
--       (RETURN NULL) и ГРОМКО в лог сервера (RAISE WARNING);
--     · любую другую правку market БЕЗ заслонки — валит RAISE EXCEPTION (условие Г-М1, см. ниже).
--
-- ПОЧЕМУ (два следствия безусловного UPDATE — ИМЕННО ОНИ, а не «лишняя запись»;
--          не «упрощать» заслонку обратно, не прочитав это):
--   (1) РАСХОЖДЕНИЕ ИСТОЧНИКА И КЭША (ADR-0002 / ADR-0018 §Amendment D3).
--       `listings.market` — ПРОИЗВОДНЫЙ кэш от species.market (колонка добавлена миграцией 0033,
--       NOT NULL). Пересчитывается РОВНО в одном месте: admin PATCH species →
--       ReferenceDataService.update() → ListingService.recomputeMarketForSpecies() (единственный
--       вызов в кодовой базе). Сырой SQL-UPDATE по species пересчёт НЕ ЗАПУСКАЕТ. Итог: species.market
--       становится 'livestock', а listings.market у уже существующих объявлений остаётся 'pet' —
--       ОБА значения проходят свои CHECK (chk_listings_market), сломано не значение, а ОТНОШЕНИЕ.
--       Самолечения нет: единственный бэкфилл (0033:56-63) идёт `WHERE l.market IS NULL`, а колонка
--       NOT NULL ⇒ он больше никогда ничего не находит. Расхождение молчит и живёт вечно.
--   (2) РОТАЦИЯ ETag ⇒ ЛОЖНЫЙ 412 (API_CONVENTIONS, ADR-0006).
--       ETag справочников выводится из updated_at: weakEtag(`species:{id}`, row.updated_at)
--       (backend/src/modules/admin/reference-data.service.ts:173, проверка If-Match — :286).
--       Безусловный UPDATE перезаписывает СТРОКУ даже когда значение то же (замерено: xmin растёт,
--       updated_at сдвигается) ⇒ на каждом `docker compose up` ETag всех строк species с этими кодами
--       меняется ⇒ условный запрос админа/ИИ-оператора получает 412 на правку, которой никто не делал.
--       Это ровно тот класс, ради которого писалась миграция 0035 (listings.content_updated_at —
--       системные записи не крутят ETag контента); здесь он был воссоздан руками провижинера.
--
-- ПОЧЕМУ ТАК, А НЕ ИНАЧЕ (форма (ii); форма (i) отклонена держателем):
--   Форма (i) — «реестр применённых миграций» (schema_migrations + пропуск уже применённых) —
--   ОТКЛОНЕНА: она меняет модель провижинера с «сходимость» (converge: replay всегда, идемпотентно,
--   CI-гейт migration-drift это доказывает) на «журнал» (apply-once), то есть отменяет свойство,
--   ради которого шаг 2 provision.ts вообще существует (лечение состарившегося тома). Плюс реестр
--   не защищает от РУЧНОГО psql-UPDATE, а лечит только один конкретный вызывающий.
--   Форма (ii) защищает ДАННЫЕ в самой БД, от любого вызывающего, и не отменяет сходимость.
--   ADR-0007 запрещает править уже применённую миграцию ⇒ 0007 остаётся дословно как есть,
--   а её эффект СУПЕРСЕДИТСЯ этой миграцией (см. provision.ts, блок KNOWN RESIDUE — этот долг).
--
-- 🔴 УСЛОВИЕ Г-М1 (несущее): подавление ГРОМКОЕ для человеческого пути, ТИХОЕ только для replay.
--   Тихо съесть чужую запись = тот самый тихий отказ, который мы выжигаем. Различитель — в САМОЙ
--   СТРОКЕ, а не в намерении:
--     · «строка НИКОГДА не проходила через админский API» ⇔ created_by IS NULL AND updated_by IS NULL
--       (админский create() штампует created_by И updated_by, update() штампует updated_by —
--       reference-data.service.ts:247-248, :305). Сид (канон:968 / 0011:20) и 0007 их не пишут.
--       Такую строку сырой bootstrap-путь ПИШЕТ СВОБОДНО — иначе на чистой установке cattle/sheep/
--       horse остались бы 'pet' (замерено: на пути «только миграции» livestock ставит ровно 0007).
--     · строка ОПЕРАТОРСКАЯ (есть created_by/updated_by) + этот UPDATE НЕ штампует нового актора
--       ⇒ это сырой replay, который отменяет решение оператора ⇒ ТИХО для вызывающего + WARNING в лог.
--     · строка ОПЕРАТОРСКАЯ + этот UPDATE ШТАМПУЕТ актора (updated_by меняется) ⇒ это живой
--       прикладной путь с ЗАБЫТОЙ заслонкой ⇒ RAISE EXCEPTION, с названием предмета и что делать.
--   ПОЧЕМУ различитель ROW-level, а не «NEW.updated_by IS NOT NULL» (первый набросок):
--   строка, которую оператор уже правил, НАВСЕГДА несёт непустой updated_by ⇒ проверка
--   «NEW.updated_by IS NOT NULL» валила бы EXCEPTION на КАЖДОМ replay ровно того сценария, который
--   мы защищаем ⇒ провижининг падал бы на каждом `compose up`, api/worker не поднимались бы.
--   Это лечение хуже болезни; поэтому «признак человека» берётся из OLD (история строки) + из
--   ИЗМЕНЕНИЯ updated_by (подпись этого statement), а не из значения NEW.
--
-- 🔴 УСЛОВИЕ Г-М2 (событие подавления обязано быть СЧИТАЕМЫМ, а не только записанным):
--   подавление помечено собственным SQLSTATE **'ZL042'**. Провижининг слушает NoticeResponse на своём
--   (единственном, provision.ts:153) соединении реплея, считает события с этим кодом и ПЕЧАТАЕТ ИТОГ
--   В СВОЁМ ВЫВОДЕ — включая «0», чтобы отсутствие строки нельзя было спутать с «строку забыли».
--   Считаем по КОДУ, а не по тексту сообщения (текст локализован, код — нет).
--   Считается ТОЛЬКО защищённое решение (пункт 4). Чистый no-op (пункт 2) НЕ считается: там нечего
--   защищать, значения уже были равны — иначе счётчик показывал бы 3 на каждом старте и умер бы как
--   сигнал. Что НЕ покрывает счётчик: правку, которую вообще не пытались сделать (её никто не видит),
--   и сырую правку по строке БЕЗ провенанса (она разрешена, пункт 4-верх).
--
-- 🔴 УСЛОВИЕ Г-М3 (ветвь 2 со стороны приложения — ЗАМЕРЕНО живым Prisma 6, не выведено):
--   `RETURN NULL` = «строка не обновлена» ⇒ `prisma.species.update()` бросает **P2025** («No record was
--   found for an update») ⇒ 500 через problem.filter (P2025 в src/ нигде не обрабатывается).
--   Прикладной путь этого НЕ ВИДИТ: пункт 1 (заслонка) стоит ПЕРЕД пунктом 2, и на живом Prisma
--   PATCH с ИДЕНТИЧНЫМ телом внутри транзакции с заслонкой прошёл нормально и `updated_at` СДВИНУЛСЯ
--   (touch-семантика и ротация ETag для прикладного пути СОХРАНЕНЫ). Сверх того пункт 2 сужен
--   отпечатком 0007 ⇒ P2025 недостижим даже при потерянной заслонке.
--
-- ОТКАТ (порядок ОБЯЗАТЕЛЕН, см. RISKS.md):
--   сначала снять триггер, только потом откатывать код:
--     DROP TRIGGER IF EXISTS trg_species_market_replay_guard ON species;
--   Обратный порядок (откат кода первым) оставляет заслонку без того, кто её поднимает ⇒ админский
--   PATCH market начнёт падать EXCEPTION (или, на no-op, P2025).
--
-- ИДЕМПОТЕНТНОСТЬ: CREATE OR REPLACE FUNCTION + DROP TRIGGER IF EXISTS/CREATE TRIGGER + COMMENT.
--   Эту миграцию гоняет тот же безусловный replay, что и все прочие: повторный прогон — no-op.
--   Проверено дважды на живом PG 16 (см. ACCEPTANCE.md).
-- ============================================================================

BEGIN;

-- Предусловие: провенанс-колонки (миграция 0018) — на них держится различитель Г-М1.
-- В порядке replay 0018 < 0042 всегда, но пусть сломается ГРОМКО И ВНЯТНО, а не в рантайме триггера.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
         WHERE table_schema = 'public' AND table_name = 'species'
           AND column_name IN ('created_by', 'updated_by')
         GROUP BY table_name HAVING count(*) = 2
    ) THEN
        RAISE EXCEPTION 'species.created_by/updated_by отсутствуют (миграция 0018) — заслонка 0042 без них не различает оператора и replay';
    END IF;
END $$;

CREATE OR REPLACE FUNCTION trg_species_market_replay_guard()
RETURNS TRIGGER AS $$
DECLARE
    -- Дословный WHERE-список migrations/20260617_0007_species_market.sql:13. Отпечаток нужен, чтобы
    -- ТИХО гасить РОВНО тот statement, который мы нейтрализуем, а не «любую сырую правку»: всякая
    -- другая сырая правка market по операторской строке обязана быть ГРОМКОЙ (Г-М1).
    replay_0007_codes CONSTANT text[] :=
        ARRAY['cattle','cow','bull','sheep','goat','pig','horse','poultry','chicken'];
BEGIN
    -- 1. Легитимный путь: транзакция подняла заслонку (admin PATCH; прецедент app.ownership_transfer).
    --    Пропускаем БЕЗ ОГРАНИЧЕНИЙ — заслонка не должна становиться вторым слоем авторизации.
    IF current_setting('app.reference_data_admin', true) IS NOT DISTINCT FROM 'on' THEN
        RETURN NEW;
    END IF;

    -- 2. Чистый no-op РОВНО от statement'а 0007: НИ ОДНА колонка не меняется, кроме updated_at (его
    --    двигает update_species_updated_at), И это отпечаток 0007. Такую запись гасим целиком — она не
    --    несёт информации, но крутит версию строки: это и есть «фоссилия» (следствие 2 + рост xmin).
    --    Сравнение через to_jsonb МИНУС updated_at: не зависит ни от порядка BEFORE-триггеров, ни от
    --    списка колонок (новая колонка species автоматически попадает в сравнение).
    --    ЗАЧЕМ здесь ещё и отпечаток (условие Г-М3, ЗАМЕРЕНО, а не выведено): `RETURN NULL` означает
    --    для клиента «строка не обновлена», и Prisma `update()` (UPDATE … RETURNING) на это бросает
    --    **P2025** «No record was found for an update» → 500 через problem.filter (замерено живым
    --    Prisma 6 на эфемерной БД, см. ACCEPTANCE §Г-М3). Прикладной путь сюда не попадает — он
    --    отсечён пунктом 1 (заслонка поднята) — но отпечаток делает P2025 НЕДОСТИЖИМЫМ даже если
    --    заслонку когда-нибудь потеряют: чужой no-op тогда просто пройдёт (пункт 3), как до пака.
    --    Гасится ТИХО и НЕ считается в Г-М2: здесь ничего не защищено — значения уже были равны.
    IF (to_jsonb(NEW) - 'updated_at') = (to_jsonb(OLD) - 'updated_at')
       AND NEW.market = 'livestock'
       AND OLD.code = ANY (replay_0007_codes) THEN
        RETURN NULL;
    END IF;

    -- 3. market фактически НЕ меняется (меняется что-то другое) — не наш предмет.
    IF NEW.market IS NOT DISTINCT FROM OLD.market THEN
        RETURN NEW;
    END IF;

    -- Дальше: заслонки нет, а market МЕНЯЕТСЯ.

    -- 4. Дословный отпечаток 0007 — ЕДИНСТВЕННЫЙ сырой писатель, которого мы знаем и терпим:
    --    актор не штампуется + целевое значение 'livestock' + код из списка 0007. Внутри — развилка
    --    по «признаку человека В СТРОКЕ»:
    --      · строка НИКОГДА не проходила через админский API (created_by и updated_by пусты) ⇒
    --        защищать нечего, это первая установка ⇒ ПИШЕМ. Именно так cattle/sheep/horse получают
    --        'livestock' (замерено: на пути «только миграции» их ставит ровно 0007);
    --      · строка ОПЕРАТОРСКАЯ ⇒ replay отменяет решение ⇒ ТИХО для вызывающего (провижининг не
    --        должен падать), но ГРОМКО в лог сервера: событие редкое и осмысленное, у него обязан
    --        быть след. Тихо И бесследно — это тот самый тихий отказ, который мы выжигаем.
    IF NEW.updated_by IS NOT DISTINCT FROM OLD.updated_by
       AND NEW.market = 'livestock'
       AND OLD.code = ANY (replay_0007_codes) THEN
        IF OLD.created_by IS NULL AND OLD.updated_by IS NULL THEN
            RETURN NEW;
        END IF;
        -- ERRCODE 'ZL042' — СЧЁТНЫЙ маркер (условие Г-М2). Провижининг считает это событие на своём
        -- соединении и печатает итог В СВОЁМ ВЫВОДЕ (provision.ts), потому что след, который никто не
        -- читает, — не свидетель. Считаем по SQLSTATE, а НЕ по тексту: язык сообщения меняется, код нет.
        -- Замерено: node-pg отдаёт это как событие 'notice' с severity='WARNING' и code='ZL042'.
        RAISE WARNING 'species.market: подавлен replay миграции 0007 по операторской строке (code=%, оставлено %, отклонено %). Источник: migrations/20260617_0007_species_market.sql — безусловный UPDATE; заслонка: миграция 0042.',
            OLD.code, OLD.market, NEW.market
            USING ERRCODE = 'ZL042';
        RETURN NULL;
    END IF;

    -- 5. Всё остальное = живой путь с ЗАБЫТОЙ заслонкой (или новый сырой писатель). ГРОМКО.
    --    Сознательно ГРОМКО и для «нетронутых» строк: сырая правка, не совпадающая с отпечатком
    --    0007, легитимного bootstrap-объяснения не имеет (канон market только DEFAULT'ит, сид
    --    только INSERT'ит, 0007 пишет только 'livestock' по своим 9 кодам).
    RAISE EXCEPTION 'species.market (code=%): правка % -> % отклонена — транзакция не подняла заслонку app.reference_data_admin.', OLD.code, OLD.market, NEW.market
        USING HINT = 'Прикладной путь: выполните в ТОЙ ЖЕ транзакции SELECT set_config(''app.reference_data_admin'',''on'',true) перед UPDATE (образец: ReferenceDataService.update / app.ownership_transfer в 0023). Правка руками: оберните в BEGIN; SELECT set_config(...); UPDATE …; COMMIT; и помните, что listings.market — производный кэш, который пересчитывает ТОЛЬКО admin PATCH (ADR-0018 §Amendment D3).';
END;
$$ LANGUAGE plpgsql;

COMMENT ON FUNCTION trg_species_market_replay_guard() IS
    'Миграция 0042: отличает сырой replay 0007 (тихо гасит, WARNING в лог) от прикладного пути '
    '(пропускает по GUC app.reference_data_admin) и от забытой заслонки (RAISE EXCEPTION, условие Г-М1). '
    'Причины: расхождение species.market с производным кэшем listings.market (ADR-0018 D3) и ротация '
    'ETag справочника ⇒ ложный 412 (ADR-0006).';

-- Имя с префиксом trg_ следует идиоме проекта (trg_animals_immutable_and_owner, trg_consents_immutable).
-- `UPDATE OF market` — заслонка не шире нужного: триггер вообще не срабатывает, если market не упомянут
-- в SET (проверено: срабатывает на упоминание, даже когда значение то же — это нужно пункту 2).
-- Порядок относительно update_species_updated_at не важен: см. комментарий в пункте 2.
DROP TRIGGER IF EXISTS trg_species_market_replay_guard ON species;
CREATE TRIGGER trg_species_market_replay_guard
    BEFORE UPDATE OF market ON species
    FOR EACH ROW EXECUTE FUNCTION trg_species_market_replay_guard();

COMMIT;
