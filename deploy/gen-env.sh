# Prod-required = (a) every key the boot validator refuses to start without in production, and
# (b) every key docker-compose.yml interpolates (an unset one silently becomes "" and breaks the
# service). (a) MIRRORS backend/src/config/env.validation.ts — the lock against drift is the unit
# test src/config/gen-env.spec.ts, which DERIVES the required set from the real zod schema and
# asserts this generator emits all of it.
REQUIRED_KEYS=(
  # (a) env.validation.ts: no .default() in envSchema, plus the production-only refines
  DATABASE_URL
  REDIS_URL
  S3_ENDPOINT
  S3_ACCESS_KEY
  S3_SECRET_KEY
  S3_BUCKET
  JWT_ACCESS_SECRET
  JWT_REFRESH_SECRET
  PHONE_HASH_PEPPER
  PII_DATA_KEY
  PII_BLIND_INDEX_KEY
  AGENT_SERVICE_SIGNING_SECRET
  METRICS_TOKEN
  # (b) docker-compose.yml ${...} interpolation
  PUBLIC_DOMAIN
  POSTGRES_USER
  POSTGRES_PASSWORD
  POSTGRES_DB
  REDIS_PASSWORD
)

# --------------------------------------------------------------------------------------------- #
# Helpers
# --------------------------------------------------------------------------------------------- #
declare -A VAL=()   # final value per key
declare -A HELD=()  # keys whose value came from the EXISTING file (never re-minted)

mint() { openssl rand -hex "$1"; }

# Read `KEY=VALUE` lines from an existing env file into VAL/HELD. Comments, blank lines and lines
# without '=' are ignored. Only NON-EMPTY values are held: an empty value means "not set" (same
# reading as the validator), so it stays eligible for filling.
load_existing() {
  local file="$1" line key value
  while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in
      '#'* | '') continue ;;
    esac
    case "$line" in
      *=*) ;;
      *) continue ;;
    esac
    key="${line%%=*}"
    value="${line#*=}"
    # Reject anything that is not a plain shell-style identifier (defensive; keeps the parser and
    # docker-compose's env_file reader in agreement).
    case "$key" in
      [A-Za-z_]*)
        [ -z "${key//[A-Za-z0-9_]/}" ] || continue
        ;;
      *) continue ;;
    esac
    if [ -n "$value" ]; then
      VAL["$key"]="$value"
      HELD["$key"]=1
    fi
  done <"$file"
}

# Fill every key in LAYOUT that has no value yet: mint if secret, else use the default, else "".
resolve_values() {
  local entry key
  for entry in "${LAYOUT[@]}"; do
    case "$entry" in
      '@'*) key="${entry#@}" ;;
      *) continue ;;
    esac
    [ -n "${VAL[$key]+set}" ] && continue
    if [ -n "${SECRET_BYTES[$key]+set}" ]; then
      VAL["$key"]="$(mint "${SECRET_BYTES[$key]}")"
    elif [ -n "${DEFAULTS[$key]+set}" ]; then
      VAL["$key"]="${DEFAULTS[$key]}"
    else
      VAL["$key"]=""
    fi
  done
  # Argument-driven, non-secret.
  [ -n "${HELD[NODE_ENV]+set}" ] || VAL[NODE_ENV]="$NODE_ENV_VALUE"
  [ -n "${HELD[PUBLIC_DOMAIN]+set}" ] || VAL[PUBLIC_DOMAIN]="$DOMAIN"
  # Derived AFTER the credentials above, so a held POSTGRES_PASSWORD is reused rather than a fresh
  # mint leaking into a connection string that no longer matches the database.
  #
  # RF RESIDENCY (ADR-0017 п.1, ФЗ-152 ст.18 ч.5): the hosts below are deliberately the COMPOSE SERVICE
  # NAMES `postgres` / `redis` — i.e. self-hosted, inside our own network. DATABASE_URL is the PRIMARY
  # store of personal data and REDIS_URL holds the counters/cached payloads derived from it, so both must
  # stay self-hosted (service name / localhost / private address / unix socket) or move under an RF domain
  # (.ru/.su/.рф). A managed FOREIGN endpoint (Neon, AWS RDS, Supabase, Upstash, Redis Cloud …) is
  # FORBIDDEN. If you HOLD an existing value (the `HELD[...]` branch above preserves whatever is already
  # in `.env`), that held value is NOT exempt: the boot validator rejects it and
  # `scripts/check-rf-residency.sh` fails. This generator does not enforce residency itself — it only
  # never introduces a violation; enforcement is layer 1 (boot) + layer 2 (the CI gate).
  [ -n "${HELD[DATABASE_URL]+set}" ] ||
    VAL[DATABASE_URL]="postgresql://${VAL[POSTGRES_USER]}:${VAL[POSTGRES_PASSWORD]}@postgres:5432/${VAL[POSTGRES_DB]}?schema=public"
  [ -n "${HELD[REDIS_URL]+set}" ] ||
    VAL[REDIS_URL]="redis://:${VAL[REDIS_PASSWORD]}@redis:6379"
  [ -n "${HELD[EMAIL_FROM]+set}" ] || VAL[EMAIL_FROM]="noreply@${VAL[PUBLIC_DOMAIN]}"
}

# Names (never values) of prod-required keys with no non-empty value.
missing_required() {
  local key
  for key in "${REQUIRED_KEYS[@]}"; do
    if [ -z "${VAL[$key]+set}" ] || [ -z "${VAL[$key]}" ]; then
      printf '%s\n' "$key"
    fi
  done
}

# Write the whole file from LAYOUT, 0600, atomically (temp + mv in the same directory).
render_to() {
  local target="$1" dir tmp entry key
  dir="$(dirname -- "$target")"
  tmp="$(mktemp "$dir/.env.gen.XXXXXX")"
  chmod 600 "$tmp"
  for entry in "${LAYOUT[@]}"; do
    case "$entry" in
      '@'*)
        key="${entry#@}"
        printf '%s=%s\n' "$key" "${VAL[$key]}"
        ;;
      *) printf '%s\n' "$entry" ;;
    esac
  done >"$tmp"
  mv -- "$tmp" "$target"
  chmod 600 "$target"
}

# Rewrite an existing file in place, changing ONLY empty-valued lines whose key is being filled,
# then append the keys that were absent entirely. Every other byte is passed through untouched.
fill_into() {
  local target="$1" dir tmp line key
  shift
  local -A fill_set=()
  local k
  for k in "$@"; do fill_set["$k"]=1; done

  dir="$(dirname -- "$target")"
  tmp="$(mktemp "$dir/.env.gen.XXXXXX")"
  chmod 600 "$tmp"

  local -A seen=()
  while IFS= read -r line || [ -n "$line" ]; do
    key=""
    case "$line" in
      '#'* | '') ;;
      *=*)
        key="${line%%=*}"
        [ -z "${key//[A-Za-z0-9_]/}" ] || key=""
        ;;
    esac
    if [ -n "$key" ] && [ -n "${fill_set[$key]+set}" ] && [ -z "${line#*=}" ]; then
      printf '%s=%s\n' "$key" "${VAL[$key]}"
      seen["$key"]=1
    else
      printf '%s\n' "$line"
      if [ -n "$key" ]; then seen["$key"]=1; fi
    fi
  done <"$target" >"$tmp"

  local appended=0
  for k in "$@"; do
    [ -n "${seen[$k]+set}" ] && continue
    if [ "$appended" -eq 0 ]; then
      printf '\n# ---- added by %s (%s) ----\n' "$PROG" "$(date -u +%Y-%m-%dT%H:%M:%SZ)" >>"$tmp"
      appended=1
    fi
    printf '%s=%s\n' "$k" "${VAL[$k]}" >>"$tmp"
  done

  mv -- "$tmp" "$target"
  chmod 600 "$target"
}

# --------------------------------------------------------------------------------------------- #
# Main
# --------------------------------------------------------------------------------------------- #
if [ ! -e "$ENV_FILE" ]; then
  # ---- CREATE ----------------------------------------------------------------------------- #
  resolve_values
  still_missing="$(missing_required || true)"
  [ -z "$still_missing" ] || die "internal: generator did not emit required key(s): $still_missing"
  render_to "$ENV_FILE"
  note "created $ENV_FILE (mode 0600) — secrets minted with 'openssl rand -hex'."
  note "minted secret keys (names only): ${!SECRET_BYTES[*]}"
  note "NODE_ENV / PUBLIC_DOMAIN set from arguments; provider credentials left EMPTY (stub mode)."
  exit 0
fi

[ -f "$ENV_FILE" ] || die "$ENV_FILE exists but is not a regular file"
[ -r "$ENV_FILE" ] || die "$ENV_FILE is not readable"

load_existing "$ENV_FILE"

if [ "$MODE" = "check" ]; then
  # ---- CHECK (default) — the file is NOT touched at all ------------------------------------ #
  missing_list="$(missing_required || true)"
  if [ -z "$missing_list" ]; then
    note "$ENV_FILE exists and is complete — all ${#REQUIRED_KEYS[@]} prod-required keys present. No changes made."
    exit 0
  fi
  note "$ENV_FILE exists — NOT modified. Missing prod-required key(s) (names only):"
  while IFS= read -r missing_key; do
    printf '  - %s\n' "$missing_key"
  done <<<"$missing_list"
  note "fix with:  $0 --fill-missing --env-file $ENV_FILE   (mints ONLY the keys listed above)"
  exit 1
fi

# ---- FILL-MISSING --------------------------------------------------------------------------- #
# Determine what is missing BEFORE resolving, so held (non-empty) values are provably untouched.
declare -a candidates=()
for entry in "${LAYOUT[@]}"; do
  case "$entry" in
    '@'*) key="${entry#@}" ;;
    *) continue ;;
  esac
  if [ -z "${HELD[$key]+set}" ]; then candidates+=("$key"); fi
done

resolve_values

# Only keys that resolve to a NON-EMPTY value are written. A key whose canonical value is the empty
# string (optional provider credential / OAuth id) is left exactly as it is — writing `KEY=` over
# `KEY=` would be a no-op, and appending it would add noise without adding configuration.
declare -a to_fill=()
for key in ${candidates[@]+"${candidates[@]}"}; do
  if [ -n "${VAL[$key]}" ]; then to_fill+=("$key"); fi
done

if [ "${#to_fill[@]}" -eq 0 ]; then
  note "$ENV_FILE already carries every key that has a value — nothing to fill, file untouched."
  exit 0
fi

fill_into "$ENV_FILE" "${to_fill[@]}"
note "filled ${#to_fill[@]} missing key(s) in $ENV_FILE (names only): ${to_fill[*]}"
note "existing non-empty values were preserved verbatim (no secret re-minted)."
exit 0
