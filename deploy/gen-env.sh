#!/usr/bin/env bash
#
# ZooLink — canonical `.env` provisioner (the ONE documented env path; ADR-0009 compose topology).
#
# WHY THIS EXISTS
#   The old documented path was `cp .env.example .env`. `.env.example` is a FORM (a commented
#   inventory of every key with placeholder values), not a provisioner: copying it verbatim yields
#   `METRICS_TOKEN=` (empty) and `__change_me__` secrets, so a NODE_ENV=production boot dies in
#   backend/src/config/env.validation.ts (`METRICS_TOKEN: required in production`). Two documented
#   paths (a form pretending to be a provisioner, and hand-editing) is exactly the drift this
#   script removes: `.env.example` stays the FORM, this script is the PATH.
#
# CONTRACT (deterministic; no interactive prompts, no guessing)
#   * `.env` ABSENT                → create it in full. Every secret is MINTED with `openssl rand
#                                    -hex` at lengths >= what env.validation.ts requires. chmod 600.
#   * `.env` PRESENT (default)     → the file is NOT touched AT ALL. Print the NAMES of the missing
#                                    prod-required keys and exit 1; exit 0 (zero changes) if none.
#   * `--fill-missing`             → mint/fill ONLY the keys that are absent or present-but-empty.
#                                    An existing NON-EMPTY value is NEVER re-minted or reformatted.
#                                    Idempotent: a second run on a complete file changes nothing.
#
#   "Missing" == absent OR present-with-an-empty-value, because the validator treats an empty
#   string as "not set" (see the METRICS_TOKEN / AGENT_SERVICE_SIGNING_SECRET blocks in
#   env.validation.ts). That is what makes `cp .env.example .env` visibly incomplete here.
#
# OUTPUT DISCIPLINE
#   This script NEVER prints a secret (or any value) to stdout/stderr — only KEY NAMES. The only
#   place values exist is the 0600 `.env` it writes.
#
# USAGE
#   deploy/gen-env.sh                              # check mode (default) — never writes
#   deploy/gen-env.sh --domain zoolink.ru          # create (only if .env is absent)
#   deploy/gen-env.sh --fill-missing               # top up an existing .env
#   deploy/gen-env.sh --env-file /path/to/.env     # operate on a non-default path (CI/tests)
#   deploy/gen-env.sh --node-env development       # default: production
#
set -euo pipefail

PROG="gen-env.sh"

die() {
  printf '%s: error: %s\n' "$PROG" "$*" >&2
  exit 2
}

note() { printf '%s: %s\n' "$PROG" "$*"; }

# --------------------------------------------------------------------------------------------- #
# Arguments
# --------------------------------------------------------------------------------------------- #
ENV_FILE=".env"
DOMAIN="localhost"
NODE_ENV_VALUE="production"
MODE="check" # check | create (implied when the file is absent) | fill

usage() {
  cat <<'USAGE'
Usage: deploy/gen-env.sh [--domain HOST] [--node-env ENV] [--fill-missing] [--env-file PATH]

  --domain HOST      PUBLIC_DOMAIN to write (default: localhost). Non-secret.
  --node-env ENV     NODE_ENV to write: development|test|production (default: production).
  --fill-missing     Top up an EXISTING .env: mint/fill only absent-or-empty keys.
  --env-file PATH    Target file (default: ./.env).
  -h, --help         This text.

Exit codes: 0 = ok / nothing to do · 1 = prod-required keys missing (check mode) · 2 = usage or
environment error.
USAGE
}

while [ $# -gt 0 ]; do
  case "$1" in
    --domain)
      [ $# -ge 2 ] || die "--domain requires a value"
      DOMAIN="$2"
      shift 2
      ;;
    --node-env)
      [ $# -ge 2 ] || die "--node-env requires a value"
      case "$2" in
        development | test | production) NODE_ENV_VALUE="$2" ;;
        *) die "--node-env must be one of: development, test, production" ;;
      esac
      shift 2
      ;;
    --env-file)
      [ $# -ge 2 ] || die "--env-file requires a value"
      ENV_FILE="$2"
      shift 2
      ;;
    --fill-missing)
      MODE="fill"
      shift
      ;;
    --check)
      MODE="check"
      shift
      ;;
    -h | --help)
      usage
      exit 0
      ;;
    *) die "unknown argument: $1 (try --help)" ;;
  esac
done

command -v openssl >/dev/null 2>&1 || die "openssl not found — required to mint secrets"

